"""The written SOP as Word and PDF, converted from the Markdown SOP (export.sop_markdown) so all
three formats always say the same thing. The Markdown is generated by us, so this handles only
the shapes it produces: headings, notes, numbered steps, bullets, sub-bullets, quotes."""

import html
import io
import re

from docx import Document
from docx.shared import Pt, RGBColor

_INLINE = re.compile(r"(\*\*[^*]+\*\*|_[^_]+_)")
GREY = RGBColor(0x5C, 0x5A, 0x55)


def _runs(text: str) -> list[tuple[str, str]]:
    """'**bold** and _italic_' -> [(text, style)] with style '', 'b' or 'i'."""
    out = []
    for part in _INLINE.split(text):
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            out.append((part[2:-2], "b"))
        elif part.startswith("_") and part.endswith("_") and len(part) > 2:
            out.append((part[1:-1], "i"))
        else:
            out.append((part, ""))
    return out


def _blocks(md: str) -> list[tuple[str, str]]:
    """Markdown lines -> (kind, text): title, h2, note, para, step, bullet, sub, quote, cite."""
    blocks = []
    for raw in md.splitlines():
        line = raw.rstrip()
        if not line:
            continue
        s = line.strip()
        if line.startswith("# "):
            blocks.append(("title", line[2:]))
        elif line.startswith("## "):
            blocks.append(("h2", line[3:]))
        elif s.startswith("> — "):
            blocks.append(("cite", s[4:]))
        elif s.startswith("> "):
            blocks.append(("quote", s[2:]))
        elif line.startswith("   - "):
            blocks.append(("sub", s[2:]))
        elif line.startswith("- "):
            blocks.append(("bullet", line[2:]))
        elif re.match(r"^\d+\. ", line):
            blocks.append(("step", line))
        elif s.startswith("_") and s.endswith("_"):
            blocks.append(("note", s.strip("_")))
        else:
            blocks.append(("para", s))
    return blocks


def sop_docx(md: str) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    for kind, text in _blocks(md):
        if kind == "title":
            doc.add_heading(text, level=0)
            continue
        if kind == "h2":
            doc.add_heading(text, level=1)
            continue
        # Steps keep the SOP's own numbers ("go to step 5" must match), not Word's auto-numbering.
        style = {"bullet": "List Bullet", "sub": "List Bullet 2"}.get(kind)
        p = doc.add_paragraph(style=style)
        if kind == "step":
            p.paragraph_format.space_before = Pt(6)
        if kind in ("quote", "cite"):
            p.paragraph_format.left_indent = Pt(28)
            p.paragraph_format.space_after = Pt(2 if kind == "quote" else 8)
        for t, st in _runs(text):
            r = p.add_run(t)
            r.bold = st == "b"
            r.italic = st == "i" or kind in ("note", "quote")
            if kind in ("note", "cite"):
                r.font.color.rgb = GREY
                r.font.size = Pt(9 if kind == "cite" else 10)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _inline_html(text: str) -> str:
    return "".join(
        f"<strong>{html.escape(t)}</strong>"
        if st == "b"
        else f"<em>{html.escape(t)}</em>"
        if st == "i"
        else html.escape(t)
        for t, st in _runs(text)
    )


def sop_html(md: str) -> str:
    """A printable HTML page (for PDF): plain serif-free document styling."""
    body, open_list = [], ""

    def close() -> None:
        nonlocal open_list
        if open_list:
            body.append(f"</{open_list}>")
            open_list = ""

    for kind, text in _blocks(md):
        want = "ul" if kind == "bullet" else open_list if kind in ("quote", "cite", "sub") else ""
        if want != open_list:
            close()
            if want:
                body.append(f"<{want}>")
                open_list = want
        if kind == "title":
            body.append(f"<h1>{_inline_html(text)}</h1>")
        elif kind == "h2":
            body.append(f"<h2>{_inline_html(text)}</h2>")
        elif kind == "step":  # the SOP's own number: "go to step 5" must match
            body.append(f'<p class="step">{_inline_html(text)}</p>')
        elif kind == "bullet":
            body.append(f"<li>{_inline_html(text)}</li>")
        elif kind == "sub":
            body.append(f'<div class="sub">• {_inline_html(text)}</div>')
        elif kind == "quote":
            body.append(f"<blockquote>{_inline_html(text)}</blockquote>")
        elif kind == "cite":
            body.append(f'<div class="cite">— {_inline_html(text)}</div>')
        else:
            body.append(f'<p class="{kind}">{_inline_html(text)}</p>')
    close()
    css = (
        "body{font:11pt/1.5 -apple-system,'Segoe UI',Helvetica,Arial,sans-serif;color:#1a1a1a;margin:0}"
        "h1{font-size:20pt;margin:0 0 6pt}h2{font-size:13pt;margin:18pt 0 6pt;border-bottom:1px solid #ddd}"
        ".note{color:#5c5a55;font-style:italic}li{margin:6pt 0 2pt}.sub{margin:2pt 0 2pt 12pt}.step{margin:10pt 0 2pt}"
        "blockquote{margin:2pt 0 0 14pt;font-style:italic;color:#333}"
        ".cite{margin:0 0 6pt 14pt;color:#5c5a55;font-size:9pt}"
    )
    head = f"<meta charset='utf-8'><style>{css}</style>"
    return f"<!doctype html><html><head>{head}</head><body>{''.join(body)}</body></html>"
